#include "llvm/ADT/ArrayRef.h"
#include "llvm/Support/CRC.h"

#include <cstdint>
#include <cstdio>
#include <cstring>

using namespace llvm;

namespace {

struct Case {
  const char *Data;
  size_t Len;
  uint32_t Crc;
  uint32_t Jam;
};

// Generated by: llvm-crc-stable --emit
const Case Cases[] = {
    {"", 0, 0x00000000U, 0xFFFFFFFFU},
    {"a", 1, 0xE8B7BE43U, 0x174841BCU},
    {"123456789", 9, 0xCBF43926U, 0x340BC6D9U},
    {"The quick brown fox jumps over the lazy dog", 43, 0x414FA339U,
     0xBEB05CC6U},
    {"\xc3\xa9\xc3\xa8\xc3\xaa \xe6\xbc\xa2\xe5\xad\x97", 13, 0x951BF774U,
     0x6AE4088BU},
    {"0123456789abcdef0123456789abcdef0123456789abcdef", 48, 0xB73BA778U,
     0x48C45887U},
};

} // namespace

int main(int Argc, char **Argv) {
  bool Emit = Argc > 1 && std::strcmp(Argv[1], "--emit") == 0;

  for (const Case &C : Cases) {
    ArrayRef<uint8_t> Data(reinterpret_cast<const uint8_t *>(C.Data), C.Len);
    uint32_t Crc = crc32(Data);
    JamCRC Jam(0xFFFFFFFFU);
    Jam.update(Data);
    uint32_t JamValue = Jam.getCRC();
    if (Emit) {
      std::printf("    {");
      std::printf("\"");
      for (size_t I = 0; I < C.Len; ++I) {
        unsigned char Ch = static_cast<unsigned char>(C.Data[I]);
        if (Ch >= 0x20 && Ch < 0x7f && Ch != '"' && Ch != '\\')
          std::printf("%c", Ch);
        else
          std::printf("\\x%02x", Ch);
      }
      std::printf("\", %zu, 0x%08XU, 0x%08XU},\n", C.Len, Crc, JamValue);
      continue;
    }
    if (Crc != C.Crc) {
      std::fprintf(stderr, "crc32 mismatch for \"%s\": %08X vs %08X\n", C.Data,
                   Crc, C.Crc);
      return 1;
    }
    if (JamValue != C.Jam) {
      std::fprintf(stderr, "JamCRC mismatch for \"%s\": %08X vs %08X\n",
                   C.Data, JamValue, C.Jam);
      return 1;
    }
  }

  if (!Emit)
    std::printf("OK: CRC values match the golden values\n");
  return 0;
}
