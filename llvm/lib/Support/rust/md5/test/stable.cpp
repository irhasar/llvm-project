//===-- stable.cpp - Golden values for llvm::MD5 --------------------------===//
//
// Built against LLVMSupport with either backend. With --emit it prints the
// initializer list, which is how the constants below are produced; without it
// the test checks the values.
//
//===----------------------------------------------------------------------===//

#include "llvm/ADT/ArrayRef.h"
#include "llvm/ADT/SmallString.h"
#include "llvm/ADT/StringRef.h"
#include "llvm/Support/MD5.h"

#include <cstdint>
#include <cstdio>
#include <cstring>

using namespace llvm;

namespace {

struct Case {
  const char *Data;
  size_t Len;
  const char *Hex;
  uint64_t Low;
  uint64_t High;
};

// Generated by: llvm-md5-stable --emit
const Case Cases[] = {
    {"", 0, "d41d8cd98f00b204e9800998ecf8427e", 0x04B2008FD98C1DD4ULL,
     0x7E42F8EC980980E9ULL},
    {"a", 1, "0cc175b9c0f1b6a831c399e269772661", 0xA8B6F1C0B975C10CULL,
     0x61267769E299C331ULL},
    {"abc", 3, "900150983cd24fb0d6963f7d28e17f72", 0xB04FD23C98500190ULL,
     0x727FE1287D3F96D6ULL},
    {"message digest", 14, "f96b697d7cb7938d525a2f31aaf161d0",
     0x8D93B77C7D696BF9ULL, 0xD061F1AA312F5A52ULL},
    {"The quick brown fox jumps over the lazy dog", 43,
     "9e107d9d372bb6826bd81d3542a419d6", 0x82B62B379D7D109EULL,
     0xD619A442351DD86BULL},
    {"0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef", 64,
     "fe3a1ff59f3b89b2ad3d33f08984874b", 0xB2893B9FF51F3AFEULL,
     0x4B878489F0333DADULL},
    {"0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef",
     128, "4fe130598d47f17c19a7c493b4ce0cf1", 0x7CF1478D5930E14FULL,
     0xF10CCEB493C4A719ULL},
};

} // namespace

int main(int Argc, char **Argv) {
  bool Emit = Argc > 1 && std::strcmp(Argv[1], "--emit") == 0;

  for (const Case &C : Cases) {
    ArrayRef<uint8_t> Data(reinterpret_cast<const uint8_t *>(C.Data), C.Len);
    MD5::MD5Result Result = MD5::hash(Data);
    SmallString<32> Hex = Result.digest();

    if (Emit) {
      std::printf("    {\"");
      for (size_t I = 0; I < C.Len; ++I) {
        unsigned char Ch = static_cast<unsigned char>(C.Data[I]);
        if (Ch >= 0x20 && Ch < 0x7f && Ch != '"' && Ch != '\\')
          std::printf("%c", Ch);
        else
          std::printf("\\x%02x", Ch);
      }
      std::printf("\", %zu, \"%s\", 0x%016llXULL, 0x%016llXULL},\n", C.Len,
                  Hex.c_str(), static_cast<unsigned long long>(Result.low()),
                  static_cast<unsigned long long>(Result.high()));
      continue;
    }

    // A mid-stream result() snapshot must not consume the state, and the same
    // bytes fed in two updates must produce the same digest.
    MD5 Split;
    size_t First = C.Len / 2;
    Split.update(Data.take_front(First));
    (void)Split.result();
    Split.update(Data.drop_front(First));
    MD5::MD5Result SplitResult;
    Split.final(SplitResult);
    if (SplitResult.digest() != Hex) {
      std::fprintf(stderr, "split update mismatch for \"%s\"\n", C.Data);
      return 1;
    }

    if (Hex != StringRef(C.Hex)) {
      std::fprintf(stderr, "digest mismatch for \"%s\": %s vs %s\n", C.Data,
                   Hex.c_str(), C.Hex);
      return 1;
    }
    if (Result.low() != C.Low || Result.high() != C.High) {
      std::fprintf(stderr, "word mismatch for \"%s\"\n", C.Data);
      return 1;
    }
  }

  if (!Emit)
    std::printf("OK: MD5 values match the golden values\n");
  return 0;
}
