//===-- stable.cpp - Golden values for llvm::SHA1 ------------------------===//
//
// Built against LLVMSupport with either backend. With --emit it prints the
// initializer list, which is how the constants below are produced; without it
// the test checks the values and exercises the incremental API.
//
//===----------------------------------------------------------------------===//

#include "llvm/ADT/ArrayRef.h"
#include "llvm/Support/SHA1.h"

#include <algorithm>
#include <cstdint>
#include <cstdio>
#include <cstring>

using namespace llvm;

namespace {

struct Case {
  const char *Data;
  size_t Len;
  const char *Hex;
};

// Generated by: llvm-sha1-stable --emit
const Case Cases[] = {
    {"", 0, "da39a3ee5e6b4b0d3255bfef95601890afd80709"},
    {"a", 1, "86f7e437faa5a7fce15d1ddcb9eaeaea377667b8"},
    {"abc", 3, "a9993e364706816aba3e25717850c26c9cd0d89d"},
    {"message digest", 14, "c12252ceda8be8994d5fa0290a47231c1d16aae3"},
    {"The quick brown fox jumps over the lazy dog", 43,
     "2fd4e1c67a2d28fced849ee1bb76e7391b93eb12"},
    {"0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef", 64,
     "ce4303f6b22257d9c9cf314ef1dee4707c6e1c13"},
    {"0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef",
     80, "bf77b0a0017bc455d1d6e93c7b807f3805a8eb9d"},
    {"0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef",
     128, "7539151d4f12a92e310f26c847cd81279b451729"},
};

} // namespace

int main(int Argc, char **Argv) {
  bool Emit = Argc > 1 && std::strcmp(Argv[1], "--emit") == 0;

  for (const Case &C : Cases) {
    ArrayRef<uint8_t> Data(reinterpret_cast<const uint8_t *>(C.Data), C.Len);
    std::array<uint8_t, 20> Result = SHA1::hash(Data);
    char Hex[41];
    for (int I = 0; I < 20; ++I)
      std::snprintf(Hex + I * 2, 3, "%02x", Result[I]);

    if (Emit) {
      std::printf("    {\"%s\", %zu, \"%s\"},\n", C.Data, C.Len, Hex);
      continue;
    }

    if (std::strcmp(Hex, C.Hex) != 0) {
      std::fprintf(stderr, "digest mismatch for \"%s\": %s vs %s\n", C.Data, Hex,
                   C.Hex);
      return 1;
    }

    // The buffered path has to agree with the one-shot hash.
    SHA1 Incremental;
    size_t Off = 0;
    size_t Chunk = 1;
    while (Off < C.Len) {
      size_t N = std::min(Chunk, C.Len - Off);
      Incremental.update(Data.slice(Off, N));
      Off += N;
      Chunk = Chunk * 3 + 1;
      if (Chunk > 37)
        Chunk = 1;
    }
    if (Incremental.final() != Result) {
      std::fprintf(stderr, "incremental mismatch for \"%s\"\n", C.Data);
      return 1;
    }
  }

  if (!Emit)
    std::printf("OK: SHA1 values match the golden values\n");
  return 0;
}
