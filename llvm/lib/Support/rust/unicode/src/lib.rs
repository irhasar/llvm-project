#[unsafe(no_mangle)]
pub extern "C" fn llvm_unicode_fold_char_simple(c: i32) -> i32 {
    if c < 0x0041 {
        return c;
    }
    if c <= 0x005a {
        return c + 32;
    }
    if c < 0x00b5 {
        return c;
    }

    let value = c as u32;
    let mut lo = 0usize;
    let mut hi = OFFSETS.len();
    while lo < hi {
        let mid = (lo + hi) / 2;
        let first = BLOCK_STARTS[mid >> BLOCK_SHIFT] + OFFSETS[mid] as u32;
        let last = first + LENGTHS[mid] as u32;
        if value < first {
            hi = mid;
        } else if value > last {
            lo = mid + 1;
        } else {
            let delta = DELTAS[mid];
            if delta > -32755 {
                return c + delta as i32;
            }
            let rank = (delta as i32 + 32768) as usize;
            return c + OUTLIER_DELTA[rank];
        }
    }
    c
}

#[cfg(test)]
mod tests {
    use super::{
        BLOCK_SHIFT, BLOCK_STARTS, DELTAS, LENGTHS, OFFSETS, OUTLIER_DELTA,
        llvm_unicode_fold_char_simple as fold,
    };

    fn delta_at(index: usize) -> i32 {
        let delta = DELTAS[index];
        if delta > -32755 {
            delta as i32
        } else {
            OUTLIER_DELTA[(delta as i32 + 32768) as usize]
        }
    }

    #[test]
    fn ascii_and_identity() {
        assert_eq!(fold(0x40), 0x40);
        assert_eq!(fold(b'A' as i32), b'a' as i32);
        assert_eq!(fold(b'z' as i32), b'z' as i32);
        assert_eq!(fold(0x7f), 0x7f);
        assert_eq!(fold(-1), -1);
    }

    #[test]
    fn known_non_ascii() {
        assert_eq!(fold(0x00b5), 0x03bc);
        assert_eq!(fold(0x0130), 0x0130);
        assert_eq!(fold(0x0178), 0x00ff);
        assert_eq!(fold(0x1e900), 0x1e922);
    }

    #[test]
    fn range_table_is_sorted_and_nonempty() {
        assert_eq!(OFFSETS.len(), LENGTHS.len());
        assert_eq!(OFFSETS.len(), DELTAS.len());
        let mut previous = None;
        for i in 0..OFFSETS.len() {
            let first = BLOCK_STARTS[i >> BLOCK_SHIFT] + OFFSETS[i] as u32;
            let last = first + LENGTHS[i] as u32;
            let delta = delta_at(i);
            assert!(first <= last);
            assert_ne!(delta, 0);
            if let Some(previous_last) = previous {
                assert!(previous_last < first);
            }
            previous = Some(last);
        }
    }

    #[test]
    fn range_endpoints_use_the_recorded_delta() {
        for i in 0..OFFSETS.len() {
            let first = BLOCK_STARTS[i >> BLOCK_SHIFT] + OFFSETS[i] as u32;
            let last = first + LENGTHS[i] as u32;
            let delta = delta_at(i);
            assert_eq!(fold(first as i32), first as i32 + delta);
            assert_eq!(fold(last as i32), last as i32 + delta);
        }
    }
}
