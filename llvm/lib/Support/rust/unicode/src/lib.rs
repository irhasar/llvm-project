#[inline]
fn block_at(mid: usize) -> usize {
    let bit = mid * 5;
    let byte = bit >> 3;
    let shift = bit & 7;
    let mut value = (BLOCK_INDEX_PACKED.get(byte).copied().unwrap_or(0) as u16) >> shift;
    if shift > 3 {
        value |= (BLOCK_INDEX_PACKED.get(byte + 1).copied().unwrap_or(0) as u16) << (8 - shift);
    }
    (value & 0x1f) as usize
}

#[inline]
fn sparse_rank(index: &[u16], mid: usize) -> usize {
    let target = mid as u16;
    let mut lo = 0usize;
    let mut hi = index.len();
    while lo < hi {
        let probe = (lo + hi) / 2;
        let value = index.get(probe).copied().unwrap_or(0);
        if value < target {
            lo = probe + 1;
        } else {
            hi = probe;
        }
    }
    if lo < index.len() && index.get(lo).copied().unwrap_or(0) == target {
        lo
    } else {
        0
    }
}

#[inline]
fn delta_at(mid: usize) -> i32 {
    let bits = DELTA_ONE.get(mid >> 3).copied().unwrap_or(0);
    if bits & (1 << (mid & 7)) != 0 {
        return 1;
    }
    let rank = sparse_rank(&OTHER_DELTA_INDEX, mid);
    OTHER_DELTA.get(rank).copied().unwrap_or(0)
}

#[unsafe(no_mangle)]
pub extern "C" fn llvm_unicode_fold_char_simple(c: i32) -> i32 {
    if c < 0x0041 {
        return c;
    }
    if c <= 0x005a {
        return c + 32;
    }
    if c < 0x00b5 {
        return c;
    }

    let value = c as u32;
    let mut lo = 0usize;
    let mut hi = OFFSETS.len();
    while lo < hi {
        let mid = (lo + hi) / 2;
        let block = block_at(mid);
        let first = BLOCK_STARTS.get(block).copied().unwrap_or(0)
            + OFFSETS.get(mid).copied().unwrap_or(0) as u32;
        let last = first + LENGTHS.get(mid).copied().unwrap_or(0) as u32;
        if value < first {
            hi = mid;
        } else if value > last {
            lo = mid + 1;
        } else {
            return c + delta_at(mid);
        }
    }
    c
}

#[cfg(test)]
mod tests {
    use super::{
        BLOCK_STARTS, LENGTHS, OFFSETS, block_at, delta_at, llvm_unicode_fold_char_simple as fold,
    };

    #[test]
    fn ascii_and_identity() {
        assert_eq!(fold(0x40), 0x40);
        assert_eq!(fold(b'A' as i32), b'a' as i32);
        assert_eq!(fold(b'z' as i32), b'z' as i32);
        assert_eq!(fold(0x7f), 0x7f);
        assert_eq!(fold(-1), -1);
    }

    #[test]
    fn known_non_ascii() {
        assert_eq!(fold(0x00b5), 0x03bc);
        assert_eq!(fold(0x0130), 0x0130);
        assert_eq!(fold(0x0178), 0x00ff);
        assert_eq!(fold(0x1e900), 0x1e922);
    }

    #[test]
    fn range_table_is_sorted_and_nonempty() {
        let mut previous = None;
        for i in 0..OFFSETS.len() {
            let first = BLOCK_STARTS[block_at(i)] + OFFSETS[i] as u32;
            let last = first + LENGTHS[i] as u32;
            let delta = delta_at(i);
            assert!(first <= last);
            assert_ne!(delta, 0);
            if let Some(previous_last) = previous {
                assert!(previous_last < first);
            }
            previous = Some(last);
        }
    }

    #[test]
    fn range_endpoints_use_the_recorded_delta() {
        for i in 0..OFFSETS.len() {
            let first = BLOCK_STARTS[block_at(i)] + OFFSETS[i] as u32;
            let last = first + LENGTHS[i] as u32;
            let delta = delta_at(i);
            assert_eq!(fold(first as i32), first as i32 + delta);
            assert_eq!(fold(last as i32), last as i32 + delta);
        }
    }
}
